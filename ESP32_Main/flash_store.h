#pragma once

#include <stddef.h>

// ที่เก็บข้อมูลก้อนใหญ่บนพาร์ทิชันไฟล์ของแฟลช (LittleFS)
//
// NVS ทั้งพาร์ทิชันมีแค่ราว 16 KB ที่ใช้ได้จริง ต้องแบ่งกับ Wi-Fi ค่าปรับเทียบคลื่นวิทยุ และบันทึกคำสั่ง
// แล้วการเขียน blob ทับของเดิมต้องมีที่ว่างเท่าขนาดใหม่ก่อนลบของเก่า ข้อมูลก้อนใหญ่ใน NVS
// จึงทำให้ที่เต็มแล้วการเขียนอื่นล้มเหลวเงียบๆ ส่วนพาร์ทิชันไฟล์ในตาราง default ของ Arduino มีราว 1.3 MB
//
// ถ้าบอร์ดใช้ตารางพาร์ทิชันที่ไม่มีพาร์ทิชันไฟล์ flashStoreReady() เป็น false
// ผู้เรียกต้องถอยกลับไปใช้ NVS แบบจำกัดจำนวน

/** เมานต์ (ครั้งแรกจะฟอร์แมต ใช้เวลาไม่กี่วินาที) เรียกก่อนโมดูลที่เก็บข้อมูลตัวอื่น */
bool flashStoreBegin();
bool flashStoreReady();

/**
 * เขียนทั้งไฟล์แบบไม่มีทางเสียครึ่งๆ กลางๆ: เขียนไฟล์ชั่วคราวจนเสร็จ แล้วเปลี่ยนชื่อทับของเดิม
 * ไฟดับระหว่างเขียน = ยังได้ไฟล์เดิมครบ ไม่ใช่ไฟล์ขาดท่อน
 */
bool flashStoreWrite(const char *path, const void *data, size_t size);

/** ขนาดไฟล์ 0 = ไม่มีไฟล์ */
size_t flashStoreSize(const char *path);

/** อ่านทั้งไฟล์ ต้องขอตรงขนาดไฟล์พอดี */
bool flashStoreRead(const char *path, void *out, size_t size);

void flashStoreRemove(const char *path);
